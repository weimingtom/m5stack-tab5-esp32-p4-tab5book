#!/usr/bin/env python3
"""Generate PDF encoding tables and the Adobe glyph-name lookup table.

Run from the project root after downloading glyphlist.txt to tools/:

    python tools/gen_pdf_tables.py
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def single_byte_table(codec: str) -> list[int]:
    table = [0] * 256
    for b in range(256):
        try:
            ch = bytes((b,)).decode(codec)
        except UnicodeDecodeError:
            continue
        if len(ch) == 1:
            table[b] = ord(ch)
    return table


def standard_encoding() -> list[int]:
    table = [0] * 256
    for b in range(0x20, 0x7F):
        table[b] = b
    table[0x27] = 0x2019  # quoteright
    table[0x60] = 0x2018  # quoteleft
    special = {
        0xA1: 0x00A1, 0xA2: 0x00A2, 0xA3: 0x00A3, 0xA4: 0x2044, 0xA5: 0x00A5,
        0xA6: 0x0192, 0xA7: 0x00A7, 0xA8: 0x00A4, 0xA9: 0x0027, 0xAA: 0x201C,
        0xAB: 0x00AB, 0xAC: 0x2039, 0xAD: 0x203A, 0xAE: 0xFB01, 0xAF: 0xFB02,
        0xB1: 0x2013, 0xB2: 0x2020, 0xB3: 0x2021, 0xB4: 0x00B7, 0xB6: 0x00B6,
        0xB7: 0x2022, 0xB8: 0x201A, 0xB9: 0x201E, 0xBA: 0x201D, 0xBB: 0x00BB,
        0xBC: 0x2026, 0xBD: 0x2030, 0xBF: 0x00BF, 0xC1: 0x0060, 0xC2: 0x00B4,
        0xC3: 0x02C6, 0xC4: 0x02DC, 0xC5: 0x00AF, 0xC6: 0x02D8, 0xC7: 0x02D9,
        0xC8: 0x00A8, 0xCA: 0x02DA, 0xCB: 0x00B8, 0xCD: 0x02DD, 0xCE: 0x02DB,
        0xCF: 0x02C7, 0xD0: 0x2014, 0xE1: 0x00C6, 0xE3: 0x00AA, 0xE8: 0x0141,
        0xE9: 0x00D8, 0xEA: 0x0152, 0xEB: 0x00BA, 0xF1: 0x00E6, 0xF5: 0x0131,
        0xF8: 0x0142, 0xF9: 0x00F8, 0xFA: 0x0153, 0xFB: 0x00DF,
    }
    for k, v in special.items():
        table[k] = v
    return table


def emit_array(name: str, table: list[int]) -> list[str]:
    lines = [f"static const uint16_t {name}[256] = {{"]
    for i in range(0, 256, 16):
        chunk = ", ".join(f"0x{v:04X}" for v in table[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return lines


def load_glyphs(path: str) -> list[tuple[str, int]]:
    glyphs: dict[str, int] = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or ";" not in line:
                continue
            name, value = line.split(";", 1)
            first = value.split(",")[0].strip()
            try:
                cp = int(first, 16)
            except ValueError:
                continue
            if cp <= 0xFFFF and name not in glyphs:
                glyphs[name] = cp
    return sorted(glyphs.items())


def main() -> int:
    glyph_path = os.path.join(ROOT, "tools", "glyphlist.txt")
    if not os.path.exists(glyph_path):
        print("tools/glyphlist.txt is missing", file=sys.stderr)
        return 1
    glyphs = load_glyphs(glyph_path)

    out = os.path.join(ROOT, "main", "reader", "pdf_tables.h")
    lines = [
        "/* Auto-generated by tools/gen_pdf_tables.py - do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint16_t uni;",
        "} pdf_glyph_name_t;",
        "",
    ]
    lines += emit_array("pdf_win_ansi", single_byte_table("cp1252"))
    lines.append("")
    lines += emit_array("pdf_mac_roman", single_byte_table("mac_roman"))
    lines.append("")
    lines += emit_array("pdf_standard_encoding", standard_encoding())
    lines += ["", f"#define PDF_GLYPH_NAME_COUNT {len(glyphs)}", ""]
    lines.append("static const pdf_glyph_name_t pdf_glyph_names[] = {")
    for name, cp in glyphs:
        lines.append(f'    {{"{name}", 0x{cp:04X}}},')
    lines += ["};", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(glyphs)} glyph names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
