"""Generate the reader's character set and the GBK -> Unicode table.

Run from the project root:

    python tools/gen_charset.py

Outputs:
    tools/charset.txt          one character per line, for lv_font_conv
    main/reader/gbk_table.h    GBK (two byte) -> Unicode BMP lookup table
"""
