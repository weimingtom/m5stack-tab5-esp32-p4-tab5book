def build_charset() -> str:
    chars: set[str] = set()

    # Printable ASCII.
    for cp in range(0x20, 0x7F):
        chars.add(chr(cp))

    # Latin-1 supplement, useful for European names and punctuation.
    for cp in range(0xA0, 0x100):
        chars.add(chr(cp))

    # Every character encodable in GB2312 (6763 ideographs + symbols, kana,
    # Greek and Cyrillic rows).
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes((hi, lo)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            chars.add(ch)

    # CJK punctuation, full-width forms, arrows and geometric shapes that
    # appear in books but are not necessarily part of GB2312.
    for start, end in (
        (0x2000, 0x206F),  # general punctuation
        (0x2190, 0x21FF),  # arrows
        (0x2200, 0x22FF),  # mathematical operators
        (0x2460, 0x24FF),  # enclosed alphanumerics
        (0x2500, 0x257F),  # box drawing
        (0x25A0, 0x25FF),  # geometric shapes
        (0x2600, 0x26FF),  # misc symbols
        (0x3000, 0x303F),  # CJK punctuation
        (0x3200, 0x32FF),  # enclosed CJK
        (0xFF00, 0xFFEF),  # half/full width forms
    ):
        for cp in range(start, end + 1):
            chars.add(chr(cp))

    chars.update(EXTRA)

    # Never include control characters or surrogates.
    out = sorted(c for c in chars if c.isprintable() and not (0xD800 <= ord(c) <= 0xDFFF))
    return "".join(out)


def gbk_table() -> list[int]:
    """Return 23940 entries: (lead-0x81)*190 + trail-index -> Unicode."""
    table = [0] * (0xFE - 0x81 + 1) * 190
    for lead in range(0x81, 0xFF):
        for trail in range(0x40, 0xFF):
            if trail == 0x7F:
                continue
            idx = (lead - 0x81) * 190 + (trail - 0x40 if trail < 0x7F else trail - 0x80 + 63)
            try:
                ch = bytes((lead, trail)).decode("gbk")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1 and ord(ch) <= 0xFFFF:
                table[idx] = ord(ch)
            elif len(ch) == 1:  # non-BMP, cannot fit; leave 0
                table[idx] = 0
    return table


def write_c_table(table: list[int], path: str) -> None:
    lines = [
        "/* Auto-generated by tools/gen_charset.py - do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define GBK_TABLE_LEADS   0xFE",
        "#define GBK_TABLE_ENTRIES 23940",
        "",
        "/* Index: (lead - 0x81) * 190 + trail_index, where trail_index is",
        " * trail - 0x40 for 0x40..0x7E and trail - 0x80 + 63 for 0x80..0xFE. */",
        "static const uint16_t gbk_to_unicode[GBK_TABLE_ENTRIES] = {",
    ]
    for i in range(0, len(table), 16):
        chunk = ", ".join(f"0x{v:04X}" for v in table[i : i + 16])
        lines.append(f"    {chunk},")
    lines += ["};", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main() -> int:
    charset = build_charset()
    charset_path = os.path.join(ROOT, "tools", "charset.txt")
    with open(charset_path, "w", encoding="utf-8", newline="\n") as f:
        for ch in charset:
            f.write(ch + "\n")

    header_path = os.path.join(ROOT, "main", "reader", "gbk_table.h")
    os.makedirs(os.path.dirname(header_path), exist_ok=True)
    write_c_table(gbk_table(), header_path)

    cjk = sum(1 for c in charset if 0x4E00 <= ord(c) <= 0x9FFF)
    print(f"charset: {len(charset)} characters ({cjk} CJK ideographs)")
    print(f"wrote {charset_path}")
    print(f"wrote {header_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
